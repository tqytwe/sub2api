package service

import (
	"context"
	"encoding/json"
	"errors"
	"fmt"

	infraerrors "github.com/Wei-Shaw/sub2api/internal/pkg/errors"
)

const ModelBillingSettingKey = "model_billing_config_v1"

var (
	ErrModelBillingSettingsUnavailable = infraerrors.ServiceUnavailable(
		"MODEL_BILLING_SETTINGS_UNAVAILABLE",
		"model billing settings storage does not support revisioned writes",
	)
	ErrModelBillingRevisionConflict = infraerrors.Conflict(
		"MODEL_BILLING_REVISION_CONFLICT",
		"model billing settings changed; reload before saving",
	)
	ErrModelBillingGroupReaderUnavailable = infraerrors.ServiceUnavailable(
		"MODEL_BILLING_GROUP_VALIDATION_UNAVAILABLE",
		"model billing group validation is not configured",
	)
)

// ModelBillingSettingsRepository is the narrow storage contract for the
// admin-only model billing policy. The revision is opaque to the service and
// is generated by the repository from the existing settings row metadata.
// Keeping it separate from SettingRepository prevents ordinary settings writes
// from accidentally bypassing compare-and-set.
type ModelBillingSettingsRepository interface {
	GetValueWithRevision(ctx context.Context, key string) (value, revision string, err error)
	CompareAndSet(ctx context.Context, key, expectedRevision, expectedValue, value string) (revision string, err error)
}

// ModelBillingGroupReader is intentionally smaller than GroupRepository so
// this policy cannot gain unrelated group mutation capabilities.
type ModelBillingGroupReader interface {
	GetByIDLite(ctx context.Context, id int64) (*Group, error)
}

// ModelBillingConfigSnapshot is the immutable policy plus storage revision
// returned to admin callers. Gateway runtime copies the policy into its request
// snapshot; reading or saving this API does not modify historical usage.
type ModelBillingConfigSnapshot struct {
	Config   ModelBillingConfig `json:"config"`
	Revision string             `json:"revision"`
}

// GetModelBillingConfig reads the dedicated key. Legacy raw JSON values remain
// readable; revision is always returned separately and never accepted from the
// policy body.
func (s *SettingService) GetModelBillingConfig(ctx context.Context) (ModelBillingConfigSnapshot, error) {
	var out ModelBillingConfigSnapshot
	if s == nil || s.settingRepo == nil {
		return out, ErrModelBillingSettingsUnavailable
	}
	repo, ok := s.settingRepo.(ModelBillingSettingsRepository)
	if !ok {
		return out, ErrModelBillingSettingsUnavailable
	}
	raw, revision, err := repo.GetValueWithRevision(ctx, ModelBillingSettingKey)
	if errors.Is(err, ErrSettingNotFound) {
		out.Config = ModelBillingConfig{}
		return out, nil
	}
	if err != nil {
		return out, err
	}
	if err := json.Unmarshal([]byte(raw), &out.Config); err != nil {
		return out, fmt.Errorf("decode model billing settings: %w", err)
	}
	out.Config = NormalizeModelBillingConfig(out.Config)
	if err := ValidateModelBillingConfig(out.Config); err != nil {
		return out, fmt.Errorf("validate model billing settings: %w", err)
	}
	out.Revision = revision
	return out, nil
}

// ValidateModelBillingConfigForAdmin validates policy fields and every scoped
// group against the current active group row when the policy is enabled.
// Disabling remains possible after a referenced group is removed or paused.
func (s *SettingService) ValidateModelBillingConfigForAdmin(ctx context.Context, cfg ModelBillingConfig) error {
	cfg = NormalizeModelBillingConfig(cfg)
	if err := ValidateModelBillingConfig(cfg); err != nil {
		return infraerrors.BadRequest("MODEL_BILLING_CONFIG_INVALID", err.Error())
	}
	if !cfg.Enabled {
		return nil
	}
	needsGroups := false
	for _, rule := range cfg.Rules {
		needsGroups = needsGroups || len(rule.GroupIDs) > 0
	}
	if !needsGroups {
		return nil
	}
	if s == nil || s.modelBillingGroupReader == nil {
		return ErrModelBillingGroupReaderUnavailable
	}
	seen := make(map[int64]struct{})
	for _, rule := range cfg.Rules {
		for _, id := range rule.GroupIDs {
			if _, ok := seen[id]; ok {
				continue
			}
			seen[id] = struct{}{}
			group, err := s.modelBillingGroupReader.GetByIDLite(ctx, id)
			if errors.Is(err, ErrGroupNotFound) {
				return infraerrors.BadRequest("MODEL_BILLING_GROUP_INVALID", fmt.Sprintf("model billing group %d does not exist", id))
			}
			if err != nil {
				return fmt.Errorf("validate model billing group %d: %w", id, err)
			}
			if group == nil || !group.IsActive() {
				return infraerrors.BadRequest("MODEL_BILLING_GROUP_INVALID", fmt.Sprintf("model billing group %d must be active", id))
			}
		}
	}
	return nil
}

// SaveModelBillingConfig performs an optimistic compare-and-set. expectedRevision
// must be the value returned by GetModelBillingConfig; an empty revision is only
// valid when the setting key does not exist yet.
func (s *SettingService) SaveModelBillingConfig(ctx context.Context, cfg ModelBillingConfig, expectedRevision string) (ModelBillingConfigSnapshot, error) {
	return s.saveModelBillingConfig(ctx, cfg, expectedRevision, nil)
}

// SaveModelBillingConfigJSON applies the admin payload to the current revision.
// Decoding into the saved config preserves scopes omitted by legacy clients.
func (s *SettingService) SaveModelBillingConfigJSON(ctx context.Context, data json.RawMessage, expectedRevision string) (ModelBillingConfigSnapshot, error) {
	return s.saveModelBillingConfig(ctx, ModelBillingConfig{}, expectedRevision, data)
}

func (s *SettingService) saveModelBillingConfig(ctx context.Context, cfg ModelBillingConfig, expectedRevision string, data json.RawMessage) (ModelBillingConfigSnapshot, error) {
	if s == nil || s.settingRepo == nil {
		return ModelBillingConfigSnapshot{}, ErrModelBillingSettingsUnavailable
	}
	repo, ok := s.settingRepo.(ModelBillingSettingsRepository)
	if !ok {
		return ModelBillingConfigSnapshot{}, ErrModelBillingSettingsUnavailable
	}
	currentRaw, currentRevision, err := repo.GetValueWithRevision(ctx, ModelBillingSettingKey)
	if errors.Is(err, ErrSettingNotFound) {
		currentRaw, currentRevision = "", ""
	} else if err != nil {
		return ModelBillingConfigSnapshot{}, err
	}
	if currentRevision != expectedRevision {
		return ModelBillingConfigSnapshot{}, ErrModelBillingRevisionConflict
	}
	if data != nil {
		if currentRaw != "" {
			if err := json.Unmarshal([]byte(currentRaw), &cfg); err != nil {
				return ModelBillingConfigSnapshot{}, fmt.Errorf("decode model billing settings: %w", err)
			}
		}
		if err := json.Unmarshal(data, &cfg); err != nil {
			return ModelBillingConfigSnapshot{}, infraerrors.BadRequest("MODEL_BILLING_CONFIG_INVALID", err.Error())
		}
	}
	cfg = NormalizeModelBillingConfig(cfg)
	if err := s.ValidateModelBillingConfigForAdmin(ctx, cfg); err != nil {
		return ModelBillingConfigSnapshot{}, err
	}
	raw, err := json.Marshal(cfg)
	if err != nil {
		return ModelBillingConfigSnapshot{}, fmt.Errorf("encode model billing settings: %w", err)
	}
	revision, err := repo.CompareAndSet(ctx, ModelBillingSettingKey, expectedRevision, currentRaw, string(raw))
	if err != nil {
		return ModelBillingConfigSnapshot{}, err
	}
	return ModelBillingConfigSnapshot{Config: cfg, Revision: revision}, nil
}

// SetModelBillingGroupReader wires the read-only group dependency used by the
// admin save path. It deliberately does not alter existing constructors.
func (s *SettingService) SetModelBillingGroupReader(reader ModelBillingGroupReader) {
	if s != nil {
		s.modelBillingGroupReader = reader
	}
}
