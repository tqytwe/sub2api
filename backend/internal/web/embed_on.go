func injectNonPublicRouteSEO(html []byte) []byte {
	result := upsertHeadTag(html, "meta", func(tag string) bool {
		return tagHasAttr(tag, "name", "robots")
	}, `<meta name="robots" content="noindex,nofollow" />`)
	result = removeMatchingTags(result, "link", func(tag string) bool {
		return tagHasAttr(tag, "rel", "canonical") || (tagHasAttr(tag, "rel", "alternate") && strings.Contains(tag, "hreflang"))
	})
	return removeRouteSEOStructuredData(result)
}

func upsertRouteSEOStructuredData(html []byte, seo routeSEO) []byte {
	result := removeRouteSEOStructuredData(html)
	payload := buildRouteSEOJSONLD(seo)
	if payload == "" {
		return result
	}
	return injectBeforeHeadClose(result, []byte(`<script type="application/ld+json" data-jisudeng-route-seo="true">`+payload+`</script>`))
}

func buildRouteSEOJSONLD(seo routeSEO) string {
	siteName := seo.SiteName
	if strings.TrimSpace(siteName) == "" {
		siteName = routeSEOAuthor
	}
	canonical := absoluteRouteSEOURL(seo.CanonicalPath)
	var graph map[string]any
	switch {
	case isHomeRoute(seo.CanonicalPath):
		organization := map[string]any{
			"@type":       "Organization",
			"name":        siteName,
			"url":         routeSEOOrigin + "/",
			"description": seo.Description,
		}
		application := map[string]any{
			"@type":               "WebApplication",
			"name":                "Jisudeng",
			"applicationCategory": "DeveloperApplication",
			"operatingSystem":     "Web",
			"description":         seo.Description,
			"url":                 canonical,
			"inLanguage":          seo.Lang,
		}
		graph = map[string]any{
			"@context": "https://schema.org",
			"@graph":   []any{organization, application},
		}
	case isCatalogLandingRoute(seo.CanonicalPath):
		entries := publicCatalogFallbackEntries(seo.Lang == "en")
		itemListName := "极速蹬公开模型系列"
		if seo.Lang == "en" {
			itemListName = "Jisudeng public model families"
		}
		items := make([]any, 0, len(entries))
		for index, entry := range entries {
			items = append(items, map[string]any{
				"@type":    "ListItem",
				"position": index + 1,
				"name":     entry.Name,
				"url":      absoluteRouteSEOURL(entry.Path),
			})
		}
		graph = map[string]any{
			"@context":        "https://schema.org",
			"@type":           "ItemList",
			"name":            itemListName,
			"description":     seo.Description,
			"url":             canonical,
			"inLanguage":      seo.Lang,
			"itemListElement": items,
		}
	default:
		return ""
	}
	payload, err := json.Marshal(graph)
	if err != nil {
		return "{}"
	}
	return string(payload)
}

func absoluteRouteSEOURL(path string) string {
	return routeSEOOrigin + path
}

func setHTMLLang(html []byte, lang string) []byte {
	return replaceFirstTag(html, "html", func(string) bool { return true }, func(tag string) string {
		return setTagAttr(tag, "lang", lang)
	})
}

func replaceTitleTag(html []byte, title string) []byte {
	titleStart := bytes.Index(html, []byte("<title>"))
	titleEnd := bytes.Index(html, []byte("</title>"))
	if titleStart == -1 || titleEnd == -1 || titleEnd <= titleStart {
		return injectBeforeHeadClose(html, []byte("<title>"+htmlpkg.EscapeString(title)+"</title>"))
	}
	var buf bytes.Buffer
	buf.Write(html[:titleStart])
	buf.WriteString("<title>")
	buf.WriteString(htmlpkg.EscapeString(title))
	buf.WriteString("</title>")
	buf.Write(html[titleEnd+len("</title>"):])
	return buf.Bytes()
}

func upsertHeadTag(html []byte, tagName string, match func(string) bool, replacement string) []byte {
	replaced := false
	result := replaceFirstTag(html, tagName, match, func(string) string {
		replaced = true
		return replacement
	})
	if replaced {
		return result
	}
	return injectBeforeHeadClose(html, []byte(replacement))
}

func replaceFirstTag(html []byte, tagName string, match func(string) bool, replacement func(string) string) []byte {
	token := []byte("<" + tagName)
	for offset := 0; offset < len(html); {
		idxOffset := bytes.Index(bytes.ToLower(html[offset:]), token)
		if idxOffset == -1 {
			return html
		}
		idx := offset + idxOffset
		endOffset := bytes.IndexByte(html[idx:], '>')
		if endOffset == -1 {
			return html
		}
		end := idx + endOffset + 1
		tag := string(html[idx:end])
		if match(strings.ToLower(tag)) {
			var buf bytes.Buffer
			buf.Write(html[:idx])
			buf.WriteString(replacement(tag))
			buf.Write(html[end:])
			return buf.Bytes()
		}
		offset = end
	}
	return html
}

func removeMatchingTags(html []byte, tagName string, match func(string) bool) []byte {
	token := []byte("<" + tagName)
	var buf bytes.Buffer
	cursor := 0
	for cursor < len(html) {
		idxOffset := bytes.Index(bytes.ToLower(html[cursor:]), token)
		if idxOffset == -1 {
			buf.Write(html[cursor:])
			break
		}
		idx := cursor + idxOffset
		endOffset := bytes.IndexByte(html[idx:], '>')
		if endOffset == -1 {
			buf.Write(html[cursor:])
			break
		}
		end := idx + endOffset + 1
		tag := strings.ToLower(string(html[idx:end]))
		if match(tag) {
			buf.Write(html[cursor:idx])
		} else {
			buf.Write(html[cursor:end])
		}
		cursor = end
	}
	return buf.Bytes()
}

func removeRouteSEOStructuredData(html []byte) []byte {
	token := []byte("<script")
	closeToken := []byte("</script>")
	var buf bytes.Buffer
	cursor := 0
	for cursor < len(html) {
		idxOffset := bytes.Index(bytes.ToLower(html[cursor:]), token)
		if idxOffset == -1 {
			buf.Write(html[cursor:])
			break
		}
		idx := cursor + idxOffset
		openEndOffset := bytes.IndexByte(html[idx:], '>')
		if openEndOffset == -1 {
			buf.Write(html[cursor:])
			break
		}
		openEnd := idx + openEndOffset + 1
		tag := strings.ToLower(string(html[idx:openEnd]))
		closeOffset := bytes.Index(bytes.ToLower(html[openEnd:]), closeToken)
		if closeOffset == -1 {
			buf.Write(html[cursor:openEnd])
			cursor = openEnd
			continue
		}
		blockEnd := openEnd + closeOffset + len(closeToken)
		if tagHasAttr(tag, "type", "application/ld+json") && tagHasAttr(tag, "data-jisudeng-route-seo", "true") {
			buf.Write(html[cursor:idx])
			cursor = blockEnd
			continue
		}
		buf.Write(html[cursor:blockEnd])
		cursor = blockEnd
	}
	return buf.Bytes()
}

func injectBeforeHeadClose(html, tag []byte) []byte {
	headClose := []byte("</head>")
	idx := bytes.Index(bytes.ToLower(html), headClose)
	if idx == -1 {
		return html
	}
	var buf bytes.Buffer
	buf.Write(html[:idx])
	buf.Write(tag)
	buf.WriteByte('\n')
	buf.Write(html[idx:])
	return buf.Bytes()
}

func tagHasAttr(tag, attr, value string) bool {
	return strings.Contains(tag, attr+`="`+strings.ToLower(value)+`"`) ||
		strings.Contains(tag, attr+`='`+strings.ToLower(value)+`'`)
}

func setTagAttr(tag, attr, value string) string {
	escaped := htmlpkg.EscapeString(value)
	lower := strings.ToLower(tag)
	for _, quote := range []byte{'"', '\''} {
		prefix := attr + "=" + string(quote)
		start := strings.Index(lower, prefix)
		if start == -1 {
			continue
		}
		valueStart := start + len(prefix)
		valueEndOffset := strings.IndexByte(tag[valueStart:], quote)
		if valueEndOffset == -1 {
			return tag
		}
		valueEnd := valueStart + valueEndOffset
		return tag[:valueStart] + escaped + tag[valueEnd:]
	}
	insertAt := len(tag) - 1
	if insertAt < 0 {
		return tag
	}
	return tag[:insertAt] + ` ` + attr + `="` + escaped + `"` + tag[insertAt:]
}

// replaceNoncePlaceholder replaces the nonce placeholder with actual nonce value
func replaceNoncePlaceholder(html []byte, nonce string) []byte {
	return bytes.ReplaceAll(html, []byte(NonceHTMLPlaceholder), []byte(nonce))
}

// ServeEmbeddedFrontend returns a middleware for serving embedded frontend
// This is the legacy function for backward compatibility when no settings provider is available
func ServeEmbeddedFrontend() gin.HandlerFunc {
	distFS, err := fs.Sub(frontendFS, "dist")
	if err != nil {
		panic("failed to get dist subdirectory: " + err.Error())
	}
	fileServer := http.FileServer(http.FS(distFS))
	overrideDir := filepath.Join("data", "public")

	return func(c *gin.Context) {
		path := c.Request.URL.Path
		if isLegacyModelsPageNavigation(c.Request) {
			setModelsCompatibilityVary(c)
			c.Redirect(http.StatusPermanentRedirect, legacyModelsCatalogLocation(c.Request))
			c.Abort()
			return
		}

		if shouldBypassEmbeddedFrontendRequest(c.Request) {
			c.Next()
			return
		}

		cleanPath := strings.TrimPrefix(path, "/")
		if cleanPath == "" {
			cleanPath = "index.html"
		}

		if cleanPath != "index.html" && tryServeOverrideFile(c, overrideDir, cleanPath) {
			return
		}

		if file, err := distFS.Open(cleanPath); err == nil {
			_ = file.Close()
			applyStaticAssetCacheHeaders(c.Writer.Header(), cleanPath)
			fileServer.ServeHTTP(c.Writer, c.Request)
			c.Abort()
			return
		}

		if isEmbeddedAssetRequest(cleanPath) {
			serveMissingEmbeddedAsset(c)
			return
		}

		serveIndexHTML(c, distFS)
	}
}

func isEmbeddedAssetRequest(cleanPath string) bool {
	return strings.HasPrefix(cleanPath, "assets/")
}

func serveMissingEmbeddedAsset(c *gin.Context) {
	c.Header("Cache-Control", "no-store")
	c.String(http.StatusNotFound, "static asset not found")
	c.Abort()
}

// tryServeOverrideFile is a standalone version of tryServeOverride for legacy usage.
func tryServeOverrideFile(c *gin.Context, overrideDir, cleanPath string) bool {
	if overrideDir == "" {
		return false
	}
	filePath := filepath.Join(overrideDir, filepath.Clean("/"+cleanPath))
	info, err := os.Stat(filePath)
	if err != nil || info.IsDir() {
		return false
	}
	c.File(filePath)
	c.Abort()
	return true
}

func shouldBypassEmbeddedFrontend(path string) bool {
	trimmed := strings.TrimSpace(path)
	return strings.HasPrefix(trimmed, "/api/") ||
		strings.HasPrefix(trimmed, "/v1/") ||
		strings.HasPrefix(trimmed, "/v1beta/") ||
		strings.HasPrefix(trimmed, "/backend-api/") ||
		strings.HasPrefix(trimmed, "/antigravity/") ||
		strings.HasPrefix(trimmed, "/setup/") ||
		trimmed == "/health" ||
		trimmed == "/home" ||
		trimmed == "/downloads/android-version.json" ||
		trimmed == "/robots.txt" ||
		trimmed == "/sitemap.xml" ||
		trimmed == "/llms.txt" ||
		trimmed == "/llms-full.txt" ||
		trimmed == "/llms.small-txt" ||
		trimmed == "/.well-known/ai.txt" ||
		trimmed == "/models" ||
		trimmed == "/responses" ||
		strings.HasPrefix(trimmed, "/responses/") ||
		trimmed == "/alpha/search" ||
		strings.HasPrefix(trimmed, "/images/") ||
		strings.HasPrefix(trimmed, "/videos/")
}

func shouldBypassEmbeddedFrontendRequest(r *http.Request) bool {
	if r == nil {
		return true
	}
	return shouldBypassEmbeddedFrontend(r.URL.Path)
}

func isLegacyModelsPageNavigation(r *http.Request) bool {
	if r == nil || !isFrontendHTMLNavigation(r) {
		return false
	}
	_, ok := legacyModelsCatalogPath(r.URL.Path)
	return ok
}

func legacyModelsCatalogLocation(r *http.Request) string {
	if r == nil {
		return "/catalog"
	}
	target, ok := legacyModelsCatalogPath(r.URL.Path)
	if !ok {
		return "/catalog"
	}
	if strings.TrimSpace(r.URL.RawQuery) == "" {
		return target
	}
	return target + "?" + r.URL.RawQuery
}

func legacyModelsCatalogPath(path string) (string, bool) {
	switch strings.TrimSpace(path) {
	case "/models":
		return "/catalog", true
	case "/en/models":
		return "/en/catalog", true
	}

	switch {
	case strings.HasPrefix(path, "/models/"):
		return "/catalog" + strings.TrimPrefix(path, "/models"), true
	case strings.HasPrefix(path, "/en/models/"):
		return "/en/catalog" + strings.TrimPrefix(path, "/en/models"), true
	default:
		return "", false
	}
}

func setModelsCompatibilityVary(c *gin.Context) {
	// These headers decide whether /models remains an API request or becomes a
	// legacy browser redirect, so every one must partition shared-cache entries.
	c.Header("Vary", "Accept, Authorization, X-API-Key, X-Goog-API-Key")
}

func setRouteSEORobotsHeader(c *gin.Context, path string) {
	if _, ok := resolveRouteSEO(path); ok {
		c.Header("X-Robots-Tag", "index, follow")
		return
	}
	c.Header("X-Robots-Tag", "noindex, nofollow")
}

func isFrontendHTMLNavigation(r *http.Request) bool {
	if r.Method != http.MethodGet && r.Method != http.MethodHead {
		return false
	}
	if r.Header.Get("Authorization") != "" ||
		r.Header.Get("x-api-key") != "" ||
		r.Header.Get("x-goog-api-key") != "" {
		return false
	}
	acceptHeader := strings.ToLower(r.Header.Get("Accept"))
	acceptsHTML := strings.Contains(acceptHeader, "text/html")
	acceptsJSON := strings.Contains(acceptHeader, "application/json")
	// Crawlers commonly send the generic media range and no browser-only
	// Sec-Fetch headers. Only that header-less shape is treated as a document;
	// browser fetches with an explicit cors/empty mode retain API semantics.
	hasFetchMetadata := strings.TrimSpace(r.Header.Get("Sec-Fetch-Mode")) != "" ||
		strings.TrimSpace(r.Header.Get("Sec-Fetch-Dest")) != "" ||
		strings.TrimSpace(r.Header.Get("Sec-Fetch-Site")) != ""
	acceptsGenericDocument := strings.EqualFold(strings.TrimSpace(r.Header.Get("Accept")), "*/*") && !hasFetchMetadata
	isDocumentNavigation := strings.EqualFold(strings.TrimSpace(r.Header.Get("Sec-Fetch-Mode")), "navigate") &&
		strings.EqualFold(strings.TrimSpace(r.Header.Get("Sec-Fetch-Dest")), "document")
	// A client may advertise both HTML and JSON (for example, an SDK that uses
	// a broad default Accept). Without browser document metadata, preserve the
	// protected API contract whenever JSON is explicitly requested.
	if acceptsJSON && !isDocumentNavigation {
		return false
	}
	return acceptsHTML || acceptsGenericDocument || isDocumentNavigation
}

func serveIndexHTML(c *gin.Context, fsys fs.FS) {
	file, err := fsys.Open("index.html")
	if err != nil {
		c.String(http.StatusNotFound, "Frontend not found")
		c.Abort()
		return
	}
	defer func() { _ = file.Close() }()

	content, err := io.ReadAll(file)
	if err != nil {
		c.String(http.StatusInternalServerError, "Failed to read index.html")
		c.Abort()
		return
	}

	setRouteSEORobotsHeader(c, c.Request.URL.Path)
	content = injectRouteSEO(content, c.Request.URL.Path)
	content = localizeEnglishHTMLShell(content, c.Request.URL.Path)
	c.Data(http.StatusOK, "text/html; charset=utf-8", content)
	c.Abort()
}

func HasEmbeddedFrontend() bool {
	_, err := frontendFS.ReadFile("dist/index.html")
	return err == nil
}

// ReadEmbeddedAsset returns a public frontend asset for compatibility routes
// that need a database-backed override with a static fallback.
func ReadEmbeddedAsset(name string) ([]byte, error) {
	return fs.ReadFile(frontendFS, "dist/"+strings.TrimLeft(name, "/"))
}
