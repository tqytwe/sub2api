// injectPublicRouteFallback gives indexable routes a semantic document when a
// crawler does not execute the SPA. The fallback lives inside #app, so Vue's
// normal mount clears it before rendering the interactive application.
func injectPublicRouteFallback(html []byte, seo routeSEO) []byte {
	const appRootOpen = `<div id="app">`
	start := bytes.Index(html, []byte(appRootOpen))
	if start == -1 {
		return html
	}
	contentStart := start + len(appRootOpen)
	endOffset := bytes.Index(html[contentStart:], []byte(`</div>`))
	if endOffset == -1 {
		return html
	}
	contentEnd := contentStart + endOffset
	if strings.TrimSpace(string(html[contentStart:contentEnd])) != "" {
		return html
	}

	fallback := []byte(buildPublicRouteFallback(seo))
	var result bytes.Buffer
	result.Write(html[:contentStart])
	result.Write(fallback)
	result.Write(html[contentEnd:])
	return result.Bytes()
}

